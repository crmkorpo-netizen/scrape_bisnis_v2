import time
import random
import pandas as pd
from bs4 import BeautifulSoup
from lxml import etree
from curl_cffi import requests

def scrape_bisnis_multi_page(start_page=1, end_page=17):
    # Modern browser headers to pass Cloudflare verification
    base_headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,image/apng,*/*;q=0.8",
        "Accept-Language": "id-ID,id;q=0.9,en-US;q=0.8,en;q=0.7",
        "Sec-Ch-Ua": '"Chromium";v="124", "Google Chrome";v="124", "Not-A.Brand";v="99"',
        "Sec-Ch-Ua-Mobile": "?0",
        "Sec-Ch-Ua-Platform": '"Windows"',
        "Sec-Fetch-Dest": "document",
        "Sec-Fetch-Mode": "navigate",
        "Sec-Fetch-Site": "same-origin",
        "Sec-Fetch-User": "?1",
        "Upgrade-Insecure-Requests": "1"
    }

    # Persistent HTTP session impersonating Chrome TLS fingerprint
    session = requests.Session(impersonate="chrome")
    session.headers.update(base_headers)

    article_urls = []

    # -------------------------------------------------------------
    # STEP 1: Iterate through index pages (Page 1 to 17) & get links
    # -------------------------------------------------------------
    print(f"--- STARTING LINK EXTRACTION (PAGES {start_page} TO {end_page}) ---")

    for page_num in range(start_page, end_page + 1):
        index_url = f"https://www.bisnis.com/index?page={page_num}"
        print(f"Fetching index page [{page_num}/{end_page}]: {index_url}")

        try:
            response = session.get(index_url, timeout=15)
            if response.status_code != 200:
                print(f"Page {page_num} failed with HTTP Status: {response.status_code}")
                continue
        except Exception as e:
            print(f"Error requesting page {page_num}: {e}")
            continue

        index_soup = BeautifulSoup(response.text, "html.parser")

        # Primary container selectors
        article_elements = index_soup.select(".list-news, .col-sm-8 .list-news, .list-berita, .artList, article, .item-news")

        page_links_found = 0
        for art in article_elements:
            link_tag = art.find("a", href=True)
            if link_tag:
                url = link_tag["href"]
                if not url.startswith("http"):
                    url = "https://www.bisnis.com" + url

                # Filter strictly for news article URLs
                if ("/read/" in url or "bisnis.com/" in url) and url not in article_urls:
                    if not url.endswith(f"/index?page={page_num}"):
                        article_urls.append(url)
                        page_links_found += 1

        # Fallback href search if layout varies on specific pages
        if page_links_found == 0:
            for a in index_soup.find_all("a", href=True):
                href = a["href"]
                if "/read/" in href:
                    full_url = href if href.startswith("http") else "https://www.bisnis.com" + href
                    if full_url not in article_urls:
                        article_urls.append(full_url)
                        page_links_found += 1

        print(f"Found {page_links_found} new articles on page {page_num}.")
        time.sleep(random.uniform(1.5, 3.0))  # Delay between index page requests

    print(f"\nTotal unique articles collected across all pages: {len(article_urls)}")
    print("--- STARTING ARTICLE DETAIL EXTRACTION ---")

    # -------------------------------------------------------------
    # STEP 2: Scrape details for each collected article URL
    # -------------------------------------------------------------
    results = []

    def fetch_with_retry(url, retries=2):
        for attempt in range(retries + 1):
            headers = {"Referer": "https://www.bisnis.com/index"}
            try:
                res = session.get(url, headers=headers, timeout=15)
                if res.status_code == 200:
                    return res
                elif res.status_code == 403:
                    print(f"HTTP 403 on {url}. Retry ({attempt + 1}/{retries})...")
                    time.sleep(random.uniform(3, 5))
            except Exception as e:
                print(f"Network error on {url}: {e}")
                time.sleep(2)
        return None

    for idx, article_url in enumerate(article_urls, 1):
        # 2 to 4 second randomized delay per article to prevent Cloudflare rate limiting
        time.sleep(random.uniform(2.0, 4.0))

        detail_res = fetch_with_retry(article_url)
        if not detail_res:
            print(f"[{idx}/{len(article_urls)}] Skipped (Persistent 403 or network error): {article_url}")
            continue

        dom = etree.HTML(detail_res.text)

        # 1. Title (Your XPath with Fallback)
        title_list = dom.xpath('//h1[contains(@class, "detailsTitleCaption")]/text()') or dom.xpath('//h1/text()')
        title = title_list[0].strip() if title_list else 'na'

        # 2. Date (Your XPath with Fallback)
        date_list = dom.xpath('//div[contains(@class, "detailsAttributeDates")]/text()') or dom.xpath('//span[contains(@class, "date")]/text()')
        date = date_list[0].strip() if date_list else 'na'

        # 3. Canonical Link (Your XPath with Fallback)
        link_list = dom.xpath('//link[@rel="canonical"]/@href')
        link = link_list[0].strip() if link_list else article_url

        # 4. Category (Your XPath)
        category_list = dom.xpath('//ul[@class="breadcrumbList"]/li[2]/a/text()')
        category = category_list[0].strip() if category_list else 'na'

        # 5. Subcategory (Your XPath)
        subcategory_list = dom.xpath('//ul[@class="breadcrumbList"]/li[contains(@class, "-active")]/a/text()')
        subcategory = subcategory_list[0].strip() if subcategory_list else 'na'

        # 6. Paragraph cleaning (Your exact BeautifulSoup decomposition logic)
        raw_paragraph = dom.xpath('//article[contains(@class, "detailsContent force-17 mt40")]') or \
                        dom.xpath('//div[contains(@class, "detailsContent")]') or \
                        dom.xpath('//article')

        clean_text = "na"
        if raw_paragraph:
            html_block = etree.tostring(raw_paragraph[0], encoding='utf-8').decode('utf-8')
            soup = BeautifulSoup(html_block, "html.parser")

            # Remove <a> tags
            for tag in soup(['a']):
                tag.decompose()

            # Remove specified div classes ('baca-juga-box' and None wrappers)
            classes = ['baca-juga-box', None]
            for c in classes:
                for data in soup('div', {'class': c}):
                    data.decompose()

            # Extract paragraphs
            p_tags = soup.find_all('p')
            if p_tags:
                paragraphs = [p.get_text(strip=True) for p in p_tags if p.get_text(strip=True)]
                clean_text = "\n\n".join(paragraphs) if paragraphs else "na"
            else:
                clean_text = soup.get_text(strip=True)

        results.append({
            'Judul': title,
            'Detail': clean_text,
            'Tanggal': date,
            'Link': link,
            'Kategori': category,
            'Sub Kategori': subcategory
        })

        print(f"[{idx}/{len(article_urls)}] Scraped: {title[:40]}...")

    return results

# Run the Scraper for pages 1 to 17
scraped_data = scrape_bisnis_multi_page(start_page=1, end_page=17)

# Load results into Pandas DataFrame
